def load_xlsx_raw(path, sheet_xml="xl/worksheets/sheet1.xml"):
    """Lit un fichier .xlsx sans dépendance externe (via zipfile + xml.etree)."""
    with zipfile.ZipFile(path) as z:
        if "xl/sharedStrings.xml" in z.namelist():
            ss_root = ET.fromstring(z.read("xl/sharedStrings.xml"))
            ns = {"ns": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
            shared = ["".join(t.text or "" for t in si.findall(".//ns:t", ns)) for si in ss_root.findall("ns:si", ns)]
        else:
            shared = []
        root = ET.fromstring(z.read(sheet_xml))
        ns = {"ns": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
        rows = root.findall(".//ns:row", ns)
        data = []
        for r in rows:
            row_dict = {}
            for c in r.findall("ns:c", ns):
                t = c.attrib.get("t")
                v = c.find("ns:v", ns)
                is_elem = c.find("ns:is", ns)
                if v is not None and v.text is not None:
                    val = shared[int(v.text)] if t == "s" else v.text
                elif is_elem is not None:
                    val = "".join(tn.text or "" for tn in is_elem.findall(".//ns:t", ns))
                else:
                    val = ""
                ref = c.attrib.get("r", "")
                col_letters = re.sub(r"\d+", "", ref)
                row_dict[col_letters] = val.strip()
            data.append(row_dict)
        return data


def load_dima_tables(g1_path="DIMA_GROUPE_1_v35-new.xlsx", g2_path="DIMA_GROUPE_2_v35-new.xlsx"):
    """Charge et unifie les deux tables DIMA (Catégorie I et Catégorie II)."""
    if not (os.path.exists(g1_path) and os.path.exists(g2_path)):
        print(
            f"[SKIP] Fichiers tiers non redistribuables absents ({g1_path}, {g2_path}) — "
            "voir DATA_PROVENANCE.md."
        )
        return pd.DataFrame()
    d1 = load_xlsx_raw(g1_path)
    d2 = load_xlsx_raw(g2_path)
    h1, h2 = d1[0], d2[0]
    df_dima = pd.DataFrame(
        [{h1.get(k, k): v for k, v in r.items()} for r in d1[1:]]
        + [{h2.get(k, k): v for k, v in r.items()} for r in d2[1:]]
    )
    df_dima["lemme_clean"] = df_dima["LEMME"].fillna("").astype(str).str.strip().str.lower()
    df_dima["sc_clean"] = df_dima["SOUS-CLASSE"].fillna("").astype(str).str.strip().str.lower()
    df_dima["cl_clean"] = df_dima["CLASSE"].fillna("").astype(str).str.strip()
    df_dima["ant_clean"] = df_dima["ANTONYMIE"].fillna("").astype(str).str.strip().str.replace("\n", " / ")
    df_dima = df_dima[df_dima["lemme_clean"] != ""].copy().reset_index(drop=True)
    return df_dima


def load_fancat_table(fancat_path="FANCatdatabaseRevisee.xlsx"):
    """Charge la base psychométrique française FANCat et normalise Valence/Arousal/Dominance dans [-1, 1]."""
    if not os.path.exists(fancat_path):
        print(
            f"[SKIP] Fichier tiers non redistribuable absent ({fancat_path}) — "
            "voir DATA_PROVENANCE.md."
        )
        return pd.DataFrame()
    f_raw = load_xlsx_raw(fancat_path, "xl/worksheets/sheet3.xml")
    fan_records = []
    for r in f_raw[2:]:
        w = r.get("A", "").strip().lower()
        if not w:
            continue
        try:
            v_fan = (float(r.get("C", 5.0)) - 5.0) / 4.0
            a_fan = (float(r.get("E", 5.0)) - 5.0) / 4.0
            pos_dom = (float(r.get("H", 1)) + float(r.get("J", 1)) + float(r.get("P", 1)) - 3.0) / 12.0
            neg_sub = (float(r.get("R", 1)) + float(r.get("X", 1)) + float(r.get("Z", 1)) - 3.0) / 12.0
            d_fan = np.clip(pos_dom - neg_sub, -1.0, 1.0)
            fan_records.append({
                "fr_clean": w,
                "v_fan": round(float(np.clip(v_fan, -1.0, 1.0)), 4),
                "a_fan": round(float(np.clip(a_fan, -1.0, 1.0)), 4),
                "d_fan": round(float(d_fan), 4),
            })
        except Exception:
            pass
    return pd.DataFrame(fan_records).drop_duplicates("fr_clean")


def get_dima_proto(rec, ref_by_label=None):
    """Résout le prototype CARTOGRAFFECT (parmi les 176) correspondant à une entrée DIMA."""
    w = str(rec.get("lemme_clean", "")).strip().lower()
    if ref_by_label:
        for p_lbl in ref_by_label:
            if p_lbl.lower() == w:
                return p_lbl
    sc = str(rec.get("sc_clean", "")).strip().lower()
    cat = str(rec.get("CATEG", "")).strip()
    cl = str(rec.get("cl_clean", "")).strip()
    if sc in DIMA_SUBCLASS_TO_PROTO:
        return DIMA_SUBCLASS_TO_PROTO[sc]
    return DIMA_CLASS_TO_PROTO.get((cat, cl), "Émoi")


def get_dima_categorie_affective(rec):
    """Détermine la catégorie affective standardisée à partir des propriétés DIMA."""
    cat = str(rec.get("CATEG", "")).strip()
    cl = str(rec.get("cl_clean", "")).strip()
    t = str(rec.get("TYPE", "")).strip()
    if "Humeur" in cl or cl in ("Apathie", "Bon moral", "Mauvais moral", "Energie"):
        return "HUMEUR"
    if cat == "I":
        return "EMOTION" if t in ("ExpAffect", "CausAffect") else "ETAT_AFFECTIF"
    if t == "ExpAffect":
        return "SENTIMENT"
    return "DISPOSITION_AFFECTIVE"

